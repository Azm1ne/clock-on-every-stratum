    def _s(x, epsilon=1e-30):                       # verbatim, utils.py:20
        return torch.where(x < 0, 1 / (1 - x + epsilon), x + 1)

    def _their_sce(logits, labels):                 # verbatim, utils.py:27,32
        sx = _s(logits.to(torch.float64))
