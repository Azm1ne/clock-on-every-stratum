def freq_norms(M, m):
    """2606.17399 Step 1 protocol: combined sin/cos norm per frequency, DC dropped."""
    k = np.arange(1, m // 2 + 1)[:, None]; t = np.arange(m)[None, :]
    s = np.sin(2 * np.pi * k * t / m) @ M
    c = np.cos(2 * np.pi * k * t / m) @ M
    return np.sqrt((s ** 2).sum(1) + (c ** 2).sum(1))


